# Type data integer
a = 10
print("Tipe data integer : {0}".format(a))

# Type data float
b = 3.14
print("Tipe data float : {0}".format(b))

# Type data Complex
c = 2 + 3j
print("Tipe data Complex : {0}".format(c))

# sequence data type
# Type data list
d = [1, 2, 3, 4, 5]
print("Tipe data list : {0}".format(d))

# tuple
e = (1, 2, 3, 4, 5)
print("Tipe data tuple : {0}".format(e))

# range
f = range(10)
print("Tipe data range : {0}".format(f))

# mapping data type
# Type data dictionary
g = {"nama": "Amin", "umur": 21, "hobi": "Membaca"}
print("Tipe data dictionary : {0}".format(g["umur"]))

# set data type
# Type data set
h = {1, 2, 3, 4, 5}
print("Tipe data set : {0}".format(h))

# froezenset
i = frozenset(f)
print("Tipe data frozenset : {0}".format(i))

# Boolean data type
# Type data boolean True (1) or False (0)
j = True
print("Tipe data boolean : {0}".format(j))
j2 = False
print("Tipe data boolean : {0}".format(j2))

# Char
huruf = 'A'
print("Tipe data char : {0}".format(huruf))
# String
k = "Hello World"
print("Tipe data string : {0}".format(k))

# Binary data type
# Type data bytes
l = 0b01000001
print("Tipe data bytes : {0}".format(l))